function submission = exportBuildingSubmission(ids, predictions, sampleFile, outputFile)
%EXPORTBUILDINGSUBMISSION Validate ordering, schema, and CSV round-trip values.
assert(iscolumn(ids) && iscolumn(predictions) && numel(ids)==numel(predictions) ...
    && ~isempty(ids) && ~any(ismissing(ids)) && numel(unique(ids))==numel(ids), ...
    'BuildingEnergy:SubmissionShape','IDs and predictions must be aligned unique-ID columns.');
assert(all(isfinite(predictions)) && all(predictions>=0), ...
    'BuildingEnergy:SubmissionValues','Predictions must be finite and nonnegative.');
sample = readtable(sampleFile,'VariableNamingRule','preserve');
assert(isequal(sample.Properties.VariableNames,{'id','site_eui'}) && ...
    isequal(sample.id,ids), 'BuildingEnergy:SubmissionTemplate', ...
    'Sample submission columns or ID ordering differ from test data.');
submission = table(ids,predictions,'VariableNames',{'id','site_eui'});
writetable(submission,outputFile);
check = readtable(outputFile,'VariableNamingRule','preserve');
assert(isequal(check.Properties.VariableNames,{'id','site_eui'}) && ...
    height(check)==numel(ids) && isequal(check.id,ids) && ...
    all(isfinite(check.site_eui)) && all(check.site_eui>=0) && ...
    all(abs(check.site_eui-predictions)<=1e-10.*max(1,abs(predictions))), ...
    'BuildingEnergy:SubmissionRoundTrip','Exported CSV failed verification.');
end
